"""Phase 5, Model 2: a shallow decision tree on all IMU features.

Calibration-sensitive features are left out (CALIBRATION_SENSITIVE): absolute
accel levels and per-axis means move with a sensor's offset/scale and gyro
bias, so a split on them (e.g. amag_mean <= 0.961, which only reflected this
sensor reading ~0.95 g at rest) would not carry over to other people or
boards. Model 2 uses variability (std, amag_std, gyro magnitude/energy),
cadence, peaks and the gravity *direction* (a unit vector) instead.

Depths 2-5 are compared on the same held-out splits as Model 1 (see
evaluation.py); the shallowest depth with the best held-out accuracy is refit
on all windows and exported as plain if/else Python (no sklearn on the board).
The export is checked against sklearn on every window before it is saved.

Works with whatever classes are present in data/windows.csv.

Outputs:
    models/model2_rules.py          predict(features) -> label, plain Python
    models/eval_model2.csv          held-out predictions (used by compare.py)
    figures/model2_confusion.png    held-out confusion matrix
    figures/model2_importance.png   feature importances (final tree)
    figures/model2_tree.png         the tree
    figures/model2_feature_space.png windows on the tree's top-2 features, with its splits

Usage:
    python laptop/model2.py
"""

import importlib.util
from datetime import date

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeClassifier, plot_tree

import plotting
from evaluation import classes_present, splits
from shared import REPO, copy_to_app, shared_features

F = shared_features()
DEPTHS = (2, 3, 4, 5)
MIN_SAMPLES_LEAF = 3
RULES = REPO / "models" / "model2_rules.py"
META_COLUMNS = ("subject", "recording", "activity", "label", "t_start", "t_end")
CALIBRATION_SENSITIVE = (
    "amag_mean", "amag_min", "amag_max",       # absolute |a| levels (scale/offset)
    "mean_ax", "mean_ay", "mean_az",           # per-axis offsets (direction is in grav_*)
    "mean_gx", "mean_gy", "mean_gz",           # gyro bias
)


def make_tree(depth):
    return DecisionTreeClassifier(max_depth=depth, min_samples_leaf=MIN_SAMPLES_LEAF, random_state=0)


def tree_to_python(clf, features, meta):
    t = clf.tree_
    lines = [
        '"""Model 2 decision tree, generated by laptop/model2.py. Do not edit by hand."""',
        "",
        f"# {meta}",
        f"FEATURES = {list(features)!r}",
        f"CLASSES = {[str(c) for c in clf.classes_]!r}",
        "",
        "",
        "def predict(f):",
        '    """f: dict of window features (shared_features.window_features). Returns a label."""',
    ]

    def uniform_label(i):
        """The label if every leaf under node i predicts the same class, else None."""
        if t.children_left[i] == -1:
            return str(clf.classes_[int(np.argmax(t.value[i]))])
        left, right = uniform_label(t.children_left[i]), uniform_label(t.children_right[i])
        return left if left is not None and left == right else None

    def node(i, depth):
        pad = "    " * depth
        label = uniform_label(i)   # collapse splits whose branches all give the same answer
        if label is not None:
            lines.append(f"{pad}return {label!r}")
            return
        lines.append(f"{pad}if f[{features[t.feature[i]]!r}] <= {float(t.threshold[i])!r}:")
        node(t.children_left[i], depth + 1)
        lines.append(f"{pad}else:")
        node(t.children_right[i], depth + 1)

    node(0, 1)
    return "\n".join(lines) + "\n"


def load_rules():
    spec = importlib.util.spec_from_file_location("model2_rules", RULES)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    windows = pd.read_csv(REPO / "data" / "windows.csv")
    features = [c for c in windows.columns if c not in META_COLUMNS and c not in CALIBRATION_SENSITIVE]
    classes = classes_present(windows, F.CLASSES)
    method, folds = splits(windows)
    X, y = windows[features], windows["label"]
    print(f"{len(windows)} windows, {len(features)} features, classes: {', '.join(classes)}")
    print(f"evaluation: {method}\n")

    held_out = {}
    for depth in DEPTHS:
        preds = pd.Series(index=windows.index, dtype=object)
        for _, tr, te in folds:
            preds.loc[te] = make_tree(depth).fit(X.loc[tr], y.loc[tr]).predict(X.loc[te])
        tested = preds.dropna().index
        held_out[depth] = (preds, plotting.accuracy(y.loc[tested], preds.loc[tested]))
        print(f"  depth {depth}: held-out accuracy {held_out[depth][1]:.1%}")
    best = max(DEPTHS, key=lambda d: (held_out[d][1], -d))   # ties -> shallower
    clf = make_tree(best).fit(X, y)
    print(f"\nchosen depth {best} (actual depth {clf.get_depth()}, {clf.get_n_leaves()} leaves)")

    meta = (f"depth {best}, trained on {len(windows)} windows from subjects "
            f"{', '.join(sorted(windows['subject'].unique()))}, classes {', '.join(classes)}; "
            f"held-out accuracy {held_out[best][1]:.1%} ({method}); {date.today().isoformat()}")
    (REPO / "models").mkdir(exist_ok=True)
    RULES.write_text(tree_to_python(clf, features, meta))
    rules = load_rules()
    exported = np.array([rules.predict(row) for row in windows[features].to_dict("records")])
    mismatch = int((exported != clf.predict(X)).sum())
    if mismatch:
        raise SystemExit(f"exported rules disagree with sklearn on {mismatch} windows")
    copy_to_app(RULES)
    print(f"exported {RULES.relative_to(REPO)} (matches sklearn on all {len(windows)} windows; "
          f"copied to unoq_app/python/models/)")

    preds = held_out[best][0]
    tested = preds.dropna().index
    ev = windows.loc[tested, ["subject", "recording", "t_start", "label"]].assign(pred=preds.loc[tested])
    ev.to_csv(REPO / "models" / "eval_model2.csv", index_label="window")

    fig, ax = plt.subplots(figsize=(5.2, 4.6))
    plotting.plot_confusion(ax, plotting.confusion(ev["label"], ev["pred"], classes), classes,
                            f"Model 2 (tree, depth {best}), held out: {held_out[best][1]:.0%}")
    fig.tight_layout()
    fig.savefig(REPO / "figures" / "model2_confusion.png", dpi=150)

    imp = pd.Series(clf.feature_importances_, index=features).sort_values()
    imp = imp[imp > 0]
    fig, ax = plt.subplots(figsize=(7, 0.45 * len(imp) + 1.4))
    ax.barh(imp.index, imp.values, color=plotting.CLASS_COLORS["standing"], height=0.6)
    for i, v in enumerate(imp.values):
        ax.text(v, i, f" {v:.2f}", va="center", color=plotting.TEXT, fontsize=10)
    ax.set_xlabel("importance (share of impurity reduction)", color=plotting.MUTED)
    ax.set_title("Model 2: features the tree uses", loc="left", color=plotting.TEXT, fontsize=12)
    plotting.style(ax, grid_axis="x")
    fig.tight_layout()
    fig.savefig(REPO / "figures" / "model2_importance.png", dpi=150)

    fig, ax = plt.subplots(figsize=(4 + 2.6 * clf.get_n_leaves(), 2.2 + 1.6 * clf.get_depth()))
    plot_tree(clf, feature_names=features, class_names=[str(c) for c in clf.classes_], filled=False,
              impurity=False, proportion=False, rounded=True, fontsize=10, ax=ax)
    ax.set_title(f"Model 2 decision tree (depth {best})", loc="left", color=plotting.TEXT, fontsize=12)
    fig.tight_layout()
    fig.savefig(REPO / "figures" / "model2_tree.png", dpi=150)

    plot_feature_space(windows, clf, features, classes, imp)
    print("saved models/eval_model2.csv and figures/model2_{confusion,importance,tree,feature_space}.png")


def plot_feature_space(windows, clf, features, classes, imp):
    top = list(imp.sort_values(ascending=False).index[:2])
    if len(top) < 2:   # tree uses a single feature: pair it with the next most variable one
        top.append(next(f for f in features if f not in top))
    fx, fy = top
    fig, ax = plt.subplots(figsize=(7, 5.5))
    for c in classes:
        w = windows[windows["label"] == c]
        ax.scatter(w[fx], w[fy], s=28, color=plotting.CLASS_COLORS[c], label=c,
                   edgecolors="white", linewidths=0.6, alpha=0.9)
    t = clf.tree_
    for i in range(t.node_count):
        if t.children_left[i] == -1:
            continue
        name = features[t.feature[i]]
        if name == fx:
            ax.axvline(t.threshold[i], color=plotting.TEXT, linestyle="--", linewidth=1)
        elif name == fy:
            ax.axhline(t.threshold[i], color=plotting.TEXT, linestyle="--", linewidth=1)
    ax.set_xlabel(fx, color=plotting.MUTED)
    ax.set_ylabel(fy, color=plotting.MUTED)
    ax.set_title("Model 2: windows on its two most important features (dashed = tree splits)",
                 loc="left", color=plotting.TEXT, fontsize=11)
    ax.legend(frameon=False)
    plotting.style(ax, grid_axis="both")
    fig.tight_layout()
    fig.savefig(REPO / "figures" / "model2_feature_space.png", dpi=150)


if __name__ == "__main__":
    main()
